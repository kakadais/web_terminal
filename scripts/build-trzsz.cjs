// Reproduce the browser protocol modules from the pinned, MIT-licensed sources.
const fs = require('node:fs');
const path = require('node:path');
const { stripTypeScriptTypes } = require('node:module');
const root = path.resolve(__dirname, '..');
for (const name of ['comm', 'buffer', 'escape', 'transfer']) {
  const source = fs.readFileSync(path.join(root, 'vendor/trzsz', `${name}.ts`), 'utf8');
  const javascript = stripTypeScriptTypes(source, { mode: 'transform' })
    .replace(/from "\.\/(comm|buffer|escape)"/g, 'from "./$1.mjs"');
  fs.writeFileSync(path.join(root, 'lib/trzsz', `${name}.mjs`), '// Generated by scripts/build-trzsz.cjs; edit vendor/trzsz instead.\n' + javascript);
}
